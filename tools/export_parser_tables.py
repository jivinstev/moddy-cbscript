#!/usr/bin/env python3
"""Export the PLY parser and lexer that scriptparse.py/scriptlex.py build, for the Java compiler.

The Java parser does not have its own grammar: it runs these exact LALR tables (state numbers included, because a
syntax error names the state it happened in) through a port of PLY 3.11's parse loop. Re-run this after ANY change
to scriptparse.py or scriptlex.py, then write/adjust the Java action for each changed production:

    python3 tools/export_parser_tables.py

Writes java/src/main/resources/com/moddingfromamod/cbscript/parser_tables.txt. CI re-runs it and fails if the file
it produces differs from the committed one.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

import scriptlex  # noqa: E402
import scriptparse  # noqa: E402

OUT = os.path.join(ROOT, 'java', 'src', 'main', 'resources', 'com', 'moddingfromamod', 'cbscript', 'parser_tables.txt')


def main():
	p = scriptparse.bparser
	lines = ['# Generated by tools/export_parser_tables.py from scriptparse.py (PLY 3.11). Do not edit.']
	for i, prod in enumerate(p.productions):
		lines.append(f'P\t{i}\t{prod.name}\t{prod.len}\t{prod.func or "-"}\t{prod.str}')
	for state in sorted(p.action):
		for tok, act in p.action[state].items():
			lines.append(f'A\t{state}\t{tok}\t{act}')
	for state in sorted(p.goto):
		for nt, st in p.goto[state].items():
			lines.append(f'G\t{state}\t{nt}\t{st}')
	for state in sorted(p.defaulted_states):
		lines.append(f'D\t{state}\t{p.defaulted_states[state]}')
	# The lexer's master regex(es), in match order, with the rule name of each named group.
	lexer = scriptlex.lexer
	for regex, findex in lexer.lexstatere['INITIAL']:
		lines.append(f'R\t{regex.pattern}')
		names = []
		for entry in findex:
			if entry is None:
				names.append('-')
			else:
				func, tok = entry
				names.append(func.__name__ if func is not None else 't_' + tok)
		lines.append('N\t' + '\t'.join(names))
	lines.append(f'I\t{lexer.lexignore!r}')
	os.makedirs(os.path.dirname(OUT), exist_ok=True)
	with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
		f.write('\n'.join(lines) + '\n')
	print(f'wrote {OUT}: {len(p.productions)} productions, {len(p.action)} states')


if __name__ == '__main__':
	main()
